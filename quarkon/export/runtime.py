"""Ollama runtime integration: daemon discovery, Modelfile generation, registration.

Deployment is a three-step, individually verifiable process:

1. **Discover** the daemon by probing ``GET {base}/api/tags`` (an HTTP endpoint
   that requires the daemon to be running). If the HTTP check fails the CLI
   reports the exact remediation (``ollama serve``).
2. **Render** a standardised ``Modelfile`` next to the GGUF artefact, containing
   the ``FROM`` line, a deterministic ``PARAMETER`` block, the DeepSeek-R1 chat
   template so ``<think>`` traces survive the runtime, the stop tokens and the
   system prompt.
3. **Register** with ``POST /api/create`` (``modelfile`` + ``name``), then
   optionally run one generation through ``POST /api/generate`` as a smoke test.

The HTTP client is injectable (``transport``) so deployment logic is covered by
tests without a running daemon.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Final

import httpx

from quarkon.core.config import PipelineConfig
from quarkon.core.exceptions import ExportError, RuntimeUnavailableError
from quarkon.core.logging import get_logger

__all__ = [
    "MODELFILE_NAME",
    "OLLAMA_CHAT_TEMPLATE",
    "DeploymentResult",
    "ModelfileSpec",
    "OllamaModel",
    "OllamaRuntime",
    "render_modelfile",
]

_log = get_logger("export.runtime")

MODELFILE_NAME: Final[str] = "Modelfile"

#: Chat template for Qwen-family / ChatML checkpoints served by Ollama.
OLLAMA_CHAT_TEMPLATE: Final[str] = (
    "{{ if .System }}<|im_start|>system\n{{ .System }}<|im_end|>\n{{ end }}"
    "{{ if .Prompt }}<|im_start|>user\n{{ .Prompt }}<|im_end|>\n{{ end }}"
    "<|im_start|>assistant\n"
    "{{ .Response }}<|im_end|>\n"
)

#: Hard stops for the Qwen/ChatML family.
CHATML_STOPS: Final[tuple[str, ...]] = ("<|im_end|>", "<|im_start|>")


@dataclass(frozen=True)
class ModelfileSpec:
    """Everything needed to render a ``Modelfile``."""

    gguf_path: Path
    model_name: str
    template: str = OLLAMA_CHAT_TEMPLATE
    system: str = ""
    parameters: Mapping[str, Any] = field(default_factory=dict)
    stops: tuple[str, ...] = CHATML_STOPS

    def render(self) -> str:
        """Render a deterministic, human-auditable Modelfile."""
        lines: list[str] = [
            "# Generated by Quarkon. Do not edit: regenerate with 'quarkon export'.",
            f"FROM {self.gguf_path.as_posix()}",
        ]
        if self.system.strip():
            lines.append("")
            lines.append('SYSTEM """' + self.system.strip().replace('"""', '\\"\\"\\"') + '"""')
        if self.template.strip():
            lines.append("")
            lines.append('TEMPLATE """' + self.template.strip() + '"""')
        if self.parameters:
            lines.append("")
            for key in sorted(self.parameters):
                lines.append(f"PARAMETER {key} {_format_parameter(self.parameters[key])}")
        for stop in self.stops:
            lines.append(f"PARAMETER stop {json.dumps(stop)}")
        return "\n".join(lines) + "\n"


def _format_parameter(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:g}"
    return str(value)


def default_parameters(config: PipelineConfig) -> dict[str, Any]:
    """Runtime defaults aligned with the synthesis sampling regime."""
    synthesis = config.synthesis
    return {
        "temperature": round(min(1.0, synthesis.temperature), 3),
        "top_p": round(synthesis.top_p, 3),
        "num_ctx": min(config.train.max_seq_length, 8192),
        "num_predict": min(synthesis.max_tokens, 4096),
        "repeat_penalty": 1.05,
    }


def render_modelfile(config: PipelineConfig, gguf_path: str | Path) -> ModelfileSpec:
    """Build the :class:`ModelfileSpec` for a configuration and artefact."""
    system = config.task.system_prompt.strip()
    if not system:
        system = f"You are a specialist assistant for this task: {config.task.objective.strip()}"
    return ModelfileSpec(
        gguf_path=Path(gguf_path).resolve(),
        model_name=config.deploy_model_name,
        system=system,
        parameters=default_parameters(config),
    )


@dataclass(frozen=True)
class OllamaModel:
    """Entry from ``GET /api/tags``."""

    name: str
    size: int
    modified_at: str
    digest: str

    @classmethod
    def from_payload(cls, payload: Mapping[str, Any]) -> OllamaModel:
        return cls(
            name=str(payload.get("name") or payload.get("model") or ""),
            size=int(payload.get("size") or 0),
            modified_at=str(payload.get("modified_at") or ""),
            digest=str(payload.get("digest") or ""),
        )


@dataclass
class DeploymentResult:
    """Outcome of registering and smoke-testing the model."""

    model_name: str
    modelfile_path: Path
    registered: bool
    smoke_test_passed: bool | None
    smoke_response: str = ""
    daemon_version: str | None = None
    base_url: str = ""
    extras: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "model_name": self.model_name,
            "modelfile_path": str(self.modelfile_path),
            "registered": self.registered,
            "smoke_test_passed": self.smoke_test_passed,
            "smoke_response": self.smoke_response[:400],
            "daemon_version": self.daemon_version,
            "base_url": self.base_url,
            **self.extras,
        }


class OllamaRuntime:
    """Thin, testable client for the local Ollama daemon."""

    def __init__(
        self,
        *,
        base_url: str = "http://localhost:11434",
        timeout_s: float = 30.0,
        transport: httpx.BaseTransport | None = None,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self._client = httpx.Client(base_url=self.base_url, timeout=timeout_s, transport=transport)

    # ------------------------------------------------------------ lifecycle
    def close(self) -> None:
        self._client.close()

    def __enter__(self) -> OllamaRuntime:
        return self

    def __exit__(self, *exc_info: object) -> None:
        self.close()

    # ------------------------------------------------------------ discovery
    def list_models(self) -> list[OllamaModel]:
        """List locally available models; raises when the daemon is unreachable."""
        try:
            response = self._client.get("/api/tags")
        except httpx.HTTPError as exc:
            raise self._unreachable(exc) from exc
        if response.status_code != 200:
            raise RuntimeUnavailableError(
                f"Ollama returned HTTP {response.status_code} for /api/tags",
                details={"base_url": self.base_url},
            )
        try:
            payload = response.json()
        except ValueError as exc:
            raise RuntimeUnavailableError(
                "Ollama /api/tags returned a non-JSON body",
                hint="another service may be listening on the configured port",
            ) from exc
        models = payload.get("models") if isinstance(payload, dict) else None
        if not isinstance(models, list):
            return []
        return [OllamaModel.from_payload(item) for item in models if isinstance(item, dict)]

    def is_available(self) -> bool:
        """Non-raising availability probe."""
        try:
            self.list_models()
        except RuntimeUnavailableError:
            return False
        return True

    def version(self) -> str | None:
        try:
            response = self._client.get("/api/version")
            if response.status_code == 200:
                data = response.json()
                if isinstance(data, dict) and data.get("version"):
                    return str(data["version"])
        except (httpx.HTTPError, ValueError):
            return None
        return None

    def has_model(self, name: str) -> bool:
        wanted = name if ":" in name else f"{name}:latest"
        for model in self.list_models():
            if model.name == name or model.name == wanted:
                return True
        return False

    # ----------------------------------------------------------- registration
    def create_from_modelfile(
        self, model_name: str, modelfile_path: Path, *, stream: bool = False
    ) -> None:
        """Register a model from a Modelfile via ``POST /api/create``."""
        if not modelfile_path.is_file():
            raise ExportError(f"Modelfile not found: {modelfile_path}")
        body = {
            "model": model_name,
            "modelfile": modelfile_path.read_text(encoding="utf-8"),
            "name": model_name,
            "stream": stream,
            "from": str(self._from_path(modelfile_path)),
        }
        try:
            response = self._client.post("/api/create", json=body)
        except httpx.HTTPError as exc:
            raise self._unreachable(exc) from exc
        if response.status_code >= 400:
            raise ExportError(
                f"Ollama refused to create model {model_name!r}: HTTP {response.status_code}: "
                f"{response.text[:500]}",
                details={"model": model_name, "status_code": response.status_code},
            )

    @staticmethod
    def _from_path(modelfile_path: Path) -> Path:
        for line in modelfile_path.read_text(encoding="utf-8").splitlines():
            if line.startswith("FROM "):
                return Path(line[5:].strip())
        return Path(".")

    def pull(self, model_name: str) -> None:
        """Pull a model from the Ollama registry (network, several GB)."""
        try:
            response = self._client.post(
                "/api/pull", json={"model": model_name, "stream": False}, timeout=3600.0
            )
        except httpx.HTTPError as exc:
            raise self._unreachable(exc) from exc
        if response.status_code >= 400:
            raise RuntimeUnavailableError(
                f"Ollama could not pull {model_name!r}: HTTP {response.status_code}: "
                f"{response.text[:300]}",
                hint="check the model name and network access, then retry",
            )

    def generate(
        self, model_name: str, prompt: str, *, options: Mapping[str, Any] | None = None
    ) -> dict[str, Any]:
        """Run a single non-streaming generation."""
        body: dict[str, Any] = {"model": model_name, "prompt": prompt, "stream": False}
        if options:
            body["options"] = dict(options)
        try:
            response = self._client.post("/api/generate", json=body)
        except httpx.HTTPError as exc:
            raise self._unreachable(exc) from exc
        if response.status_code >= 400:
            raise ExportError(
                f"generation failed with HTTP {response.status_code}: {response.text[:400]}",
                details={"model": model_name},
            )
        data = response.json()
        if not isinstance(data, dict):
            raise ExportError("Ollama /api/generate returned an unexpected body")
        return data

    # -------------------------------------------------------------- helpers
    def _unreachable(self, exc: BaseException) -> RuntimeUnavailableError:
        return RuntimeUnavailableError(
            f"cannot reach the Ollama daemon at {self.base_url}: {type(exc).__name__}: {exc}",
            hint=(
                "start it with 'ollama serve' (or set deploy.ollama_base_url) and verify "
                f"{self.base_url}/api/tags responds"
            ),
            details={"base_url": self.base_url},
        )


def deploy(
    config: PipelineConfig,
    gguf_path: str | Path,
    *,
    runtime: OllamaRuntime | None = None,
    modelfile_path: Path | None = None,
) -> DeploymentResult:
    """Render the Modelfile, register the model and run the smoke test."""
    spec = render_modelfile(config, gguf_path)
    target = modelfile_path or (Path(config.deploy.models_dir) / config.task.name / MODELFILE_NAME)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(spec.render(), encoding="utf-8", newline="\n")
    _log.info("deploy.modelfile_written", path=str(target), model=spec.model_name)

    owns_runtime = runtime is None
    rt = runtime or OllamaRuntime(
        base_url=config.deploy.ollama_base_url, timeout_s=config.deploy.request_timeout_s
    )
    try:
        daemon_version = rt.version()
        if not rt.is_available():
            raise RuntimeUnavailableError(
                f"Ollama daemon is not reachable at {config.deploy.ollama_base_url}",
                hint=(
                    "start it with 'ollama serve'; the model was exported but not registered"
                ),
            )
        registered = False
        smoke_passed: bool | None = None
        smoke_response = ""
        if config.deploy.upload:
            rt.create_from_modelfile(spec.model_name, target)
            registered = True
            _log.info("deploy.registered", model=spec.model_name)
        if config.deploy.smoke_test:
            prompt = f"Give one short example request for this task: {config.task.objective}"
            payload = rt.generate(spec.model_name, prompt, options=spec.parameters)
            smoke_response = str(payload.get("response") or "")
            smoke_passed = bool(smoke_response.strip())
            _log.info(
                "deploy.smoke_test",
                passed=smoke_passed,
                chars=len(smoke_response),
            )
        return DeploymentResult(
            model_name=spec.model_name,
            modelfile_path=target,
            registered=registered,
            smoke_test_passed=smoke_passed,
            smoke_response=smoke_response,
            daemon_version=daemon_version,
            base_url=config.deploy.ollama_base_url,
        )
    finally:
        if owns_runtime:
            rt.close()
